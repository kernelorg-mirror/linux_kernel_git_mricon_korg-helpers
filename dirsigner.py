from packaging.version import InvalidVersion, Version

VERSION = '0.2'
# Big enough that hashing a multi-gigabyte tarball is not dominated by read()
# syscalls. Overridable with -b, but there is rarely a reason to.
CHUNK_SIZE = 262144
HASH_ALGORITHMS = ('md5', 'sha1', 'sha256', 'sha512')

INDEX_FILE = 'index.html'
# Width of the name column in the index, matching nginx's autoindex module
INDEX_NAME_WIDTH = 50
# First line of every index.html we write, so we can tell our own listings
# apart from hand-written ones and leave those alone. Deliberately carries no
# version or timestamp: it has to stay byte-stable, or every run would find
# every listing different and rewrite the lot.
INDEX_MARKER = b'<!-- generated by dirsigner, do not edit -->'

logger = logging.getLogger('dirsigner')


class FileStatus(TypedDict):
    """What we remember about a file between runs.

    If any of ctime, mtime, size or inode changed, the file is rehashed.
    """

    ctime: int
    mtime: int
    size: int
    inode: int
    hash: str


def _safe_version(s: str) -> Version:
    try:
        return Version(s)
    except InvalidVersion:
        return Version('0')


def parse_args() -> argparse.Namespace:
    global CHUNK_SIZE

    parser = argparse.ArgumentParser(
        description='Iterate recursively through a tree and create signed checksum files',
    )
    parser.add_argument('--version', action='version', version=VERSION)
    parser.add_argument('-v', '--verbose', dest='verbose', action='store_true',
                        default=False,
                        help='Be verbose and tell us what you are doing')
    parser.add_argument('-t', '--tree', dest='tree', required=True,
                        help='The tree to recursively scan')
    parser.add_argument('-a', '--hash-algorithm', dest='hash_algorithm',
                        default='sha256',
                        help=('Hashing algorithm to use (sha256 default, '
                              'but can be %s)' % ', '.join(HASH_ALGORITHMS)))
    parser.add_argument('-g', '--gnupghome', dest='gnupghome',
                        default=None,
                        help='Set GNUPGHOME to this path (default: use ~/.gnupg)')
    parser.add_argument('-x', '--exclude', dest='excludes', action='append',
                        default=[],
                        help='Exclude files matching this glob (can be used multiple times)')
    parser.add_argument('-l', '--log-file', dest='logfile',
                        default=None,
                        help='Path to the log file (default: %(default)s)')
    parser.add_argument('-d', '--debug', dest='debug', action='store_true',
                        default=False,
                        help='Add debugging information to the log (default: %(default)s)')
    parser.add_argument('-s', '--version-sort', dest='vsort', action='store_true',
                        default=False,
                        help='Sort entries in the sums file by version (default: %(default)s)')
    parser.add_argument('-i', '--index', dest='index', action='store_true',
                        default=False,
                        help=('Also write an nginx-style index.html in every directory '
                              '(default: %(default)s)'))
    parser.add_argument('-u', '--url-prefix', dest='urlprefix',
                        default='/',
                        help=('URL path the tree is served under, used in index.html '
                              'titles (default: %(default)s)'))
    parser.add_argument('-k', '--lock-file', dest='lockfile',
                        default='.dirsigner.lock',
                        help='Path to the lockfile (default: %(default)s)')
    parser.add_argument('-b', '--chunk-bytes', dest='chunksize', type=int,
                        default=CHUNK_SIZE,
                        help='Calculate checksum using chunks of this size (default: %(default)s)')

    opts = parser.parse_args()

    CHUNK_SIZE = opts.chunksize

    if opts.hash_algorithm not in HASH_ALGORITHMS:
        parser.error('Unsupported algorithm: %s' % opts.hash_algorithm)

    return opts


def get_version_info(filen: str) -> tuple[str, Version, str]:
    basen = os.path.basename(filen)
    # split by last dash
    nv = basen.rsplit('-', 1)
    if len(nv) != 2:
        return basen, _safe_version('0'), ''

    name, end = nv

    chunks = end.split('.')
    tail: list[str] = list()
    while len(chunks):
        if re.search(r'\D', chunks[-1]):
            tail.append(chunks.pop(-1))
            continue
        break

    if chunks:
        ver = _safe_version('.'.join(chunks))
    else:
        ver = _safe_version('0')

    return name, ver, '.'.join(tail)


def load_status(statusfile: str) -> dict[str, FileStatus]:
    # Opened without checking first: the open tells us whether it is there,
    # and this runs once per directory in the tree.
    try:
        with open(statusfile, 'r') as fh:
            contents = fh.read()
    except FileNotFoundError:
        logger.debug('No status file found, assuming initial run')
        return {}

    logger.debug('Read status file from %s' % statusfile)
    status: dict[str, FileStatus] = json.loads(contents)
    logger.debug('Status file contains %d entries' % len(status.keys()))

    return status


def save_status(statusfile: str, status: dict[str, FileStatus]) -> None:
    if not len(status):
        # Nothing left to remember, so don't leave an empty stub behind
        try:
            os.unlink(statusfile)
            logger.debug('Removed obsolete %s' % statusfile)
        except FileNotFoundError:
            pass
        return

    logger.debug('Saving status into %s' % statusfile)
    logger.debug('Status contains %d entries' % len(status.keys()))
    contents = json.dumps(status)
    fh = open(statusfile, 'w')
    fh.write(contents)
    fh.close()


def get_file_hash(full_path: str, hash_algorithm: str) -> str:
    if hash_algorithm == 'md5':
        m = hashlib.md5()
    elif hash_algorithm == 'sha1':
        m = hashlib.sha1()
    elif hash_algorithm == 'sha512':
        m = hashlib.sha512()
    else:
        m = hashlib.sha256()

    logger.debug('Opening %s for reading using %d-byte chunks' % (full_path, CHUNK_SIZE))
    with open(full_path, 'rb') as fh:
        for chunk in iter(lambda: fh.read(CHUNK_SIZE), b''):
            m.update(chunk)

    return m.hexdigest()


def format_size(size: int) -> str:
    """Render a file size the way nginx's autoindex module does."""
    if size > 1024 ** 3 - 1:
        scale, unit = 1024 ** 3, 'G'
    elif size > 1024 ** 2 - 1:
        scale, unit = 1024 ** 2, 'M'
    elif size > 9999:
        scale, unit = 1024, 'K'
    else:
        return '%d' % size

    # nginx rounds to the nearest whole unit instead of truncating
    scaled = size // scale
    if size % scale > scale // 2 - 1:
        scaled += 1

    return '%d%s' % (scaled, unit)


def format_index_entry(name: str, mtime: int, size: int | None) -> str:
    """Format one line of a directory index, nginx autoindex style.

    Pass size=None for a subdirectory, which gets a '-' in the size column.
    Names longer than the name column are shown truncated, but always link
    to the full name.
    """
    if len(name) > INDEX_NAME_WIDTH:
        shown = html.escape(name[:INDEX_NAME_WIDTH - 3], quote=False) + '..&gt;'
        padding = ''
    else:
        shown = html.escape(name, quote=False)
        padding = ' ' * (INDEX_NAME_WIDTH - len(name))

    stamp = time.strftime('%d-%b-%Y %H:%M', time.gmtime(mtime))
    column = '-' if size is None else format_size(size)

    # One space after the padded name, then the size right-aligned in 8
    return '<a href="%s">%s</a>%s %s%8s' % (urllib.parse.quote(name), shown, padding, stamp, column)


def stat_index_entry(root: str, name: str) -> str | None:
    """Format an index entry for something we have to look at on disk.

    Symlinks are followed, the way the server's autoindex followed them, so
    a link shows its target's size and mtime and a link to a directory is
    listed as one. A dangling link falls back to the link itself. Returns
    None if we can't stat it at all.
    """
    full_path = os.path.join(root, name)
    try:
        fstat = os.stat(full_path)
    except OSError:
        try:
            fstat = os.lstat(full_path)
        except OSError:
            logger.debug('Was not able to stat %s, leaving it out of the index' % full_path)
            return None

    if stat.S_ISDIR(fstat.st_mode):
        return format_index_entry(name + '/', int(fstat.st_mtime), None)

    return format_index_entry(name, int(fstat.st_mtime), fstat.st_size)


def render_index(urlpath: str, entries: list[str]) -> bytes:
    """Wrap formatted entries in the page nginx would have served.

    Identical to autoindex output apart from the marker comment on the first
    line, which is how we recognise our own work later. An empty directory
    still gets a page, holding nothing but the link to the parent, because
    that is what autoindex served for one.
    """
    title = html.escape(urlpath, quote=False)
    lines = [
        INDEX_MARKER.decode('utf-8'),
        '<html>',
        '<head><title>Index of %s</title></head>' % title,
        '<body>',
        '<h1>Index of %s</h1><hr><pre><a href="../">../</a>' % title,
    ]
    lines += entries
    lines += ['</pre><hr></body>', '</html>', '']

    return '\r\n'.join(lines).encode('utf-8')


# Returned for an index.html we must not touch, as opposed to None for one
# that is simply not there yet.
NOT_OURS = b'\x00not ours'


def read_our_index(index_file: str) -> bytes | None:
    """Read an existing index.html, but only if we are the ones who wrote it.

    Returns its contents, None if there is nothing there, or NOT_OURS if the
    file exists but we did not generate it and must leave it alone. Anything
    without our marker on the first line is somebody's hand-written page, and
    a symlink is never ours because we never make one.
    """
    try:
        # O_NOFOLLOW so a symlink fails here rather than being read through.
        # Doing it in the open, instead of an lstat first, means there is no
        # window in which the file could be swapped for a link under us.
        fd = os.open(index_file, os.O_RDONLY | os.O_NOFOLLOW)
    except FileNotFoundError:
        return None
    except OSError as ex:
        # ELOOP is the symlink case; anything else is a file we cannot read,
        # and either way the safe answer is to keep our hands off it.
        # Debug, not info: this is a standing state of the tree rather than
        # something we just did, so at info it would repeat on every run.
        logger.debug('Not touching %s: %s' % (index_file, ex.strerror))
        return NOT_OURS

    with open(fd, 'rb') as ifh:
        contents = ifh.read()

    if not contents.startswith(INDEX_MARKER):
        logger.debug('Not touching %s: we did not generate it' % index_file)
        return NOT_OURS

    return contents


def write_index_file(root: str, urlpath: str, found_files: list[str], subdirs: list[str],
                     status: dict[str, FileStatus], hash_algorithm: str,
                     symlinks: list[str]) -> None:
    """Write index.html for a single directory.

    Subdirectories come first, then the files in the same order they appear
    in the sums file, then any symlinks, then the sums file itself. Dotfiles
    are left out, the way nginx leaves them out. Sizes and mtimes for the
    checksummed files come from the status we already collected, so the only
    stat calls here are for subdirectories, symlinks and the sums file.

    A hand-written index.html is left exactly as it is, so this never
    destroys a page somebody put there on purpose.
    """
    index_file = os.path.join(root, INDEX_FILE)
    entries = []

    for name in subdirs:
        entry = stat_index_entry(root, name)
        if entry is not None:
            entries.append(entry)

    for name in found_files:
        if name.startswith('.'):
            continue
        if name in status:
            entries.append(format_index_entry(name, status[name]['mtime'], status[name]['size']))
            continue
        entry = stat_index_entry(root, name)
        if entry is not None:
            entries.append(entry)

    # Symlinks are listed but never checksummed, so they are not in status
    # and we have to look at them on disk.
    for name in symlinks:
        if name.startswith('.'):
            continue
        entry = stat_index_entry(root, name)
        if entry is not None:
            entries.append(entry)

    # The sums file is excluded from its own checksums, but it should still
    # show up in the listing, same as it did with the server's autoindex.
    sums_name = hash_algorithm + 'sums.asc'
    entry = stat_index_entry(root, sums_name)
    if entry is not None:
        entries.append(entry)

    contents = render_index(urlpath, entries)

    existing = read_our_index(index_file)
    if existing is NOT_OURS:
        return
    if existing == contents:
        # Only write when something actually changed, so we don't churn mtimes
        logger.debug('%s is already up to date' % index_file)
        return

    with open(index_file, 'wb') as ifh:
        ifh.write(contents)

    logger.info('Wrote %s' % index_file)


def write_sums_file(root: str, found_files: list[str], status: dict[str, FileStatus],
                    hash_algorithm: str) -> None:
    # Clean out any stale sums files, including the one we are about to
    # replace. Unlinked blind rather than stat'ed first: most of these four
    # are not there, and the unlink tells us that just as well.
    for supported_algorithm in HASH_ALGORITHMS:
        sums_file = os.path.join(root, supported_algorithm + 'sums.asc')
        try:
            os.unlink(sums_file)
        except FileNotFoundError:
            pass

    if not len(found_files):
        return

    tfh = BytesIO()
    for filename in found_files:
        checksum = status[filename]['hash']
        tfh.write(('%s  %s\n' % (checksum, filename)).encode('utf-8'))

    tfh.seek(0)

    sums_file = os.path.join(root, hash_algorithm + 'sums.asc')
    cfh = open(sums_file, 'wb')

    ctx = gpg.Context(armor=True)
    ctx.sign(tfh, cfh, mode=gpg.constants.sig.mode.CLEAR)

    tfh.close()
    cfh.close()
    logger.info('Wrote %s' % sums_file)


def sign_tree(tree: str, excludes: list[str], hash_algorithm: str, vsort: bool = False,
              index: bool = False, urlprefix: str = '/') -> None:
    logger.info('Recursively scanning %s' % tree)

    # Make sure '*sums.asc' and .dirsigner.* are always in excludes
    if '*sums.asc' not in excludes:
        excludes.append('*sums.asc')
    if '.dirsigner.*' not in excludes:
        excludes.append('.dirsigner.*')
    # index.html is written after the sums file, so it can never be in it
    if index and INDEX_FILE not in excludes:
        excludes.append(INDEX_FILE)

    logger.debug('Exclude list: %s' % ' '.join(excludes))

    prefix = '/' + urlprefix.strip('/')
    if not prefix.endswith('/'):
        prefix += '/'

    for root, dirs, files in os.walk(tree, topdown=True):
        logger.debug('Entered %s' % root)

        statusfile = os.path.join(root, '.dirsigner.status.js')
        status = load_status(statusfile)

        found_files: list[str] = []
        found_links: list[str] = []
        dir_changed = False

        for name in files:
            full_path = os.path.join(root, name)

            # Does it match excludes?
            excluded = False
            for exclude in excludes:
                if fnmatch.fnmatch(name, exclude) or fnmatch.fnmatch(full_path, exclude):
                    logger.debug('Excluding %s because it matches %s' % (full_path, exclude))
                    excluded = True
                    break
            if excluded:
                continue

            # Get stats on the file and compare to what we have in the status.
            # This is the only stat we make per file, so everything below has
            # to come out of st_mode rather than calling os.path.islink and
            # friends, which would stat all over again.
            try:
                fstat = os.lstat(full_path)
            except OSError:
                logger.debug('Was not able to stat %s, ignoring' % full_path)
                continue

            if stat.S_ISLNK(fstat.st_mode):
                # Listed in the index, but never checksummed: the target is
                # either elsewhere in the tree and signed there, or outside it.
                logger.debug('Not checksumming symlink %s' % name)
                found_links.append(name)
                continue

            found_files.append(name)
            # Whole seconds only, which is what the tuple form of stat used to give us
            ctime = int(fstat.st_ctime)
            mtime = int(fstat.st_mtime)
            size = fstat.st_size
            inode = fstat.st_ino

            # Is this path in status?
            changed = False
            if name in status:
                # Do ctime, mtime and size match?
                # A bit verbose, but lets us log the exact reason
                if status[name]['ctime'] != ctime:
                    logger.info('File %s changed ctime' % name)
                    changed = True
                elif status[name]['mtime'] != mtime:
                    logger.info('File %s changed mtime' % name)
                    changed = True
                elif status[name]['size'] != size:
                    logger.info('File %s changed size' % name)
                    changed = True
                elif status[name]['inode'] != inode:
                    logger.info('File %s changed inode' % name)
                    changed = True
            else:
                logger.debug('No previous record of %s' % name)
                changed = True

            if changed:
                file_hash = get_file_hash(full_path, hash_algorithm)

                dir_changed = True
                logger.info('%s hash of %s is: %s' % (hash_algorithm, full_path, file_hash))

                status[name] = {
                    'ctime': ctime,
                    'mtime': mtime,
                    'size': size,
                    'inode': inode,
                    'hash': file_hash,
                    }

        # Weed out status entries for files that are no longer there. Uses a
        # set because directories here can hold thousands of files, and a
        # linear scan of found_files per entry makes this quadratic.
        present = set(found_files)
        for entry in list(status.keys()):
            if entry not in present:
                logger.info('File %s from status is no longer there' % entry)
                del status[entry]
                dir_changed = True

        sums_file = os.path.join(root, hash_algorithm + 'sums.asc')
        if len(found_files) and not os.path.exists(sums_file):
            # Always generate one if we don't have it
            dir_changed = True

        # Sorted here rather than in write_sums_file, so that the index
        # lists files in exactly the order the sums file does. Without
        # vsort that is whatever order the filesystem handed us, which we
        # must not change: it would rewrite and re-sign every sums file.
        if vsort:
            # Debug rather than info: this runs for every directory on every
            # run now, whether anything changed or not.
            logger.debug('Version-sorting %s' % root)
            found_files.sort(key=get_version_info)

        if dir_changed:
            write_sums_file(root, found_files, status, hash_algorithm)
            # Save status after each changed dir
            save_status(statusfile, status)

        # Look at dirs and see if we need to exclude any of them
        to_rm: list[str] = []
        for name in dirs:
            full_path = os.path.join(root, name)

            # No islink check here: os.walk never descends into a symlinked
            # directory anyway, and skipping the exclude check for one meant
            # -x could not keep it out of the index.
            excluded = False
            for exclude in excludes:
                if fnmatch.fnmatch(name, exclude) or fnmatch.fnmatch(full_path, exclude):
                    logger.debug('Excluding %s because it matches %s' % (full_path, exclude))
                    excluded = True
                    break
            if excluded:
                to_rm.append(name)
                continue

        for name in to_rm:
            dirs.remove(name)

        if index:
            # Subdirectories sort by name, which is what the server's
            # autoindex did. version_sort would be no help here: it needs a
            # name-version-extension filename and treats everything else as
            # version 0. Sorting also makes the walk order stable.
            dirs.sort()

            # Symlinks were never in a sums file, so unlike the files above
            # there is no published order to preserve and we can just sort.
            found_links.sort(key=get_version_info if vsort else None)

            relpath = os.path.relpath(root, tree)
            urlpath = prefix if relpath == '.' else prefix + relpath + '/'
            write_index_file(root, urlpath, found_files, dirs, status, hash_algorithm,
                             found_links)


def main() -> None:
    opts = parse_args()

    logger.setLevel(logging.DEBUG)

    ch = logging.StreamHandler()
    formatter = logging.Formatter('%(message)s')
    ch.setFormatter(formatter)

    if opts.verbose:
        ch.setLevel(logging.INFO)
    else:
        ch.setLevel(logging.CRITICAL)

    logger.addHandler(ch)

    if opts.logfile is not None:
        fh = logging.FileHandler(opts.logfile)
        formatter = logging.Formatter("[%(process)d] %(asctime)s - %(levelname)s - %(message)s")
        fh.setFormatter(formatter)

        if opts.debug:
            fh.setLevel(logging.DEBUG)
        else:
            fh.setLevel(logging.INFO)

        logger.addHandler(fh)

    if opts.gnupghome is not None:
        logger.info('Setting GNUPGHOME to %s' % opts.gnupghome)
        os.environ['GNUPGHOME'] = opts.gnupghome

    lock_fh = open(opts.lockfile, 'w')
    logger.debug('Obtaining exclusive lock for %s' % opts.lockfile)

    try:
        lockf(lock_fh, LOCK_EX | LOCK_NB)
    except IOError:
        logger.info('Could not obtain exclusive lock, assuming another process is running.')
        sys.exit(128)

    logger.debug('Lock obtained')

    sign_tree(opts.tree, opts.excludes, opts.hash_algorithm, vsort=opts.vsort,
              index=opts.index, urlprefix=opts.urlprefix)
    lockf(lock_fh, LOCK_UN)
    logger.debug('Lock released')


if __name__ == '__main__':
    main()
